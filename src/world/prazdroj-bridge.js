export function identifyPrazdrojBridge(roads) {
  const id = 32249;
  if (roads.cls[id] !== RC.FOOTWAY || !(roads.flags[id] & RF.BRIDGE)
      || roads.x0[id] !== 6648 || roads.z0[id] !== 1793) return -1;
  let x = roads.x0[id], z = roads.z0[id];
  for (let k = roads.start[id]; k < roads.start[id + 1]; k++) {
    x += roads.dx[k];
    z += roads.dz[k];
  }
  return x === 6511 && z === 1353 ? id : -1;
}
